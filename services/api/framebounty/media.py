"""Private local storage and bounded ffprobe checks; no authenticity claims.

All object keys are generated by the service. Client filenames are never used as
paths. Production workers also need OS/container CPU and memory limits; a process
timeout alone cannot enforce a total decoder-memory budget on every platform.
"""
import hashlib
import json
import os
import re
import shutil
import subprocess
from dataclasses import dataclass
from decimal import Decimal, InvalidOperation
from pathlib import Path

MAX_UPLOAD = 100 * 1024 * 1024


class InvalidMedia(ValueError):
    pass


class MediaUnavailable(RuntimeError):
    pass


class LocalStorage:
    def __init__(self, root: str | Path | None = None):
        self.root = Path(root or os.getenv("STORAGE_ROOT", ".local/media")).resolve()
        self.root.mkdir(parents=True, exist_ok=True)

    def path(self, key: str) -> Path:
        if not re.fullmatch(r"[0-9a-f]{32}\.(?:video|upload|jpg)", key):
            raise InvalidMedia("Invalid storage key")
        result = (self.root / key).resolve()
        if result.parent != self.root:
            raise InvalidMedia("Storage path escapes private root")
        return result

    def sha256(self, key: str) -> str:
        digest = hashlib.sha256()
        with self.path(key).open("rb") as source:
            for chunk in iter(lambda: source.read(1024 * 1024), b""):
                digest.update(chunk)
        return digest.hexdigest()


def validate_container_header(header: bytes):
    # MP4/MOV is the first supported upload family. Header detection is only an
    # early rejection heuristic; ffprobe and full decode remain mandatory.
    if len(header) < 12 or header[4:8] != b"ftyp":
        raise InvalidMedia("Upload an MP4 or MOV video; file content did not match")


@dataclass(frozen=True)
class VideoMetadata:
    duration_ms: int
    width: int
    height: int
    codec: str


def validate_probe(payload: dict) -> VideoMetadata:
    try:
        if not isinstance(payload, dict) or not isinstance(payload.get("streams"), list) or any(not isinstance(s, dict) for s in payload["streams"]):
            raise InvalidMedia("Invalid stream metadata")
        videos = [s for s in payload["streams"] if s.get("codec_type") == "video"]
        if len(videos) != 1:
            raise InvalidMedia("Exactly one video stream is required")
        video = videos[0]
        width, height = int(video["width"]), int(video["height"])
        # Metadata time is not money; decimal text is converted without float rounding.
        duration = Decimal(str(payload["format"]["duration"]))
        if not duration.is_finite() or duration < 10 or duration > 30:
            raise InvalidMedia("Video must be 10–30 seconds long")
        if min(width, height) < 240 or max(width, height) > 3840 or width * height > 3840 * 2160:
            raise InvalidMedia("Video dimensions are outside supported limits")
        codec = video["codec_name"]
        if codec not in {"h264", "hevc", "mpeg4"}:
            raise InvalidMedia("Unsupported video codec; use H.264 or HEVC in MP4/MOV")
        rate = str(video.get("avg_frame_rate", "0/1"))
        numerator, denominator = rate.split("/")
        fps = Decimal(numerator) / Decimal(denominator)
        if not fps.is_finite() or not 1 <= fps <= 60:
            raise InvalidMedia("Video must use 1–60 frames per second")
        return VideoMetadata(int(duration * 1000), width, height, codec)
    except (KeyError, TypeError, ValueError, ArithmeticError, InvalidOperation) as exc:
        if isinstance(exc, InvalidMedia):
            raise
        raise InvalidMedia("Video metadata is invalid or incomplete") from exc


def inspect_video(path: Path) -> VideoMetadata:
    executable = media_executable("ffprobe")
    if not executable:
        raise MediaUnavailable("ffprobe is not installed; verification cannot run")
    try:
        result = subprocess.run([executable, "-v", "error", "-protocol_whitelist", "file,pipe",
            "-show_entries", "stream=codec_type,codec_name,width,height,avg_frame_rate:format=duration",
            "-of", "json", str(path.resolve())], capture_output=True, timeout=15, check=False)
    except subprocess.TimeoutExpired as exc:
        raise InvalidMedia("Video probe exceeded its time limit") from exc
    if result.returncode or len(result.stdout) > 64 * 1024:
        raise InvalidMedia("Video is corrupt or cannot be probed safely")
    try:
        return validate_probe(json.loads(result.stdout))
    except (json.JSONDecodeError, UnicodeDecodeError) as exc:
        raise InvalidMedia("Invalid video probe output") from exc


def decode_video(path: Path):
    """Decode the entire bounded clip; metadata alone cannot establish a valid file."""
    executable = media_executable("ffmpeg")
    if not executable:
        raise MediaUnavailable("ffmpeg is not installed; verification cannot run")
    try:
        result = subprocess.run([executable, "-v", "error", "-xerror", "-nostdin",
            "-protocol_whitelist", "file,pipe", "-threads", "1", "-i", str(path.resolve()),
            "-map", "0:v:0", "-an", "-t", "31", "-progress", "pipe:1", "-stats_period", "1", "-f", "null", "-"],
            stdout=subprocess.PIPE, stderr=subprocess.DEVNULL, timeout=45, check=False)
    except subprocess.TimeoutExpired as exc:
        raise InvalidMedia("Video decoding exceeded its time limit") from exc
    if result.returncode:
        raise InvalidMedia("Video cannot be decoded completely")
    if len(result.stdout) > 128 * 1024:
        raise InvalidMedia("Decoder progress exceeded its output limit")
    times = [int(line.split(b"=", 1)[1]) for line in result.stdout.splitlines() if line.startswith(b"out_time_us=") and line.split(b"=", 1)[1].isdigit()]
    if not times or max(times) < 9_500_000 or max(times) > 30_100_000:
        raise InvalidMedia("Decoded video timing is outside supported limits")


def media_executable(name: str) -> str | None:
    configured = os.getenv(name.upper() + "_BIN")
    if configured:
        return configured
    portable = Path(__file__).resolve().parents[3] / ".local" / "ffmpeg" / (name + ".exe")
    if os.name == "nt" and portable.is_file():
        return str(portable)
    return shutil.which(name)


def sample_frames(path: Path, storage: LocalStorage, duration_ms: int) -> list[dict]:
    """Five bounded, timestamped samples. Similarity is a review flag, never rejection."""
    import secrets
    import warnings
    import imagehash
    from PIL import Image, ImageFilter, ImageStat

    executable = media_executable("ffmpeg")
    if not executable:
        raise MediaUnavailable("ffmpeg is not installed")
    frames = []
    created = []
    try:
        for timestamp in sorted({0, duration_ms // 4, duration_ms // 2, duration_ms * 3 // 4, max(0, duration_ms - 250)}):
            key = secrets.token_hex(16) + ".jpg"
            target = storage.path(key)
            created.append(target)
            try:
                result = subprocess.run([executable, "-v", "error", "-nostdin", "-protocol_whitelist", "file,pipe",
                    "-threads", "1", "-ss", f"{timestamp / 1000:.3f}", "-i", str(path.resolve()),
                    "-frames:v", "1", "-vf", "scale=640:640:force_original_aspect_ratio=decrease",
                    "-q:v", "3", "-y", str(target)], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
                    timeout=15, check=False)
            except subprocess.TimeoutExpired as exc:
                raise InvalidMedia("Frame extraction exceeded its time limit") from exc
            if result.returncode or not target.exists() or target.stat().st_size > 2_000_000:
                raise InvalidMedia("Could not extract a bounded frame")
            with warnings.catch_warnings():
                warnings.simplefilter("error", Image.DecompressionBombWarning)
                with Image.open(target) as image:
                    if image.width * image.height > 640 * 640:
                        raise InvalidMedia("Sample frame is unexpectedly large")
                    gray = image.convert("L")
                    frames.append({"key": key, "timestamp_ms": timestamp, "dhash": str(imagehash.dhash(gray)),
                        "brightness": round(ImageStat.Stat(gray).mean[0], 2),
                        "edge_variance": round(ImageStat.Stat(gray.filter(ImageFilter.FIND_EDGES)).var[0], 2)})
        return frames
    except BaseException:
        for target in created:
            target.unlink(missing_ok=True)
        raise
